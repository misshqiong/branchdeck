const { contextBridge, ipcRenderer } = require('electron');
const invoke = (channel, ...args) => ipcRenderer.invoke(channel, ...args).then(result => { if (!result.ok) throw new Error(result.error); return result.value; });
contextBridge.exposeInMainWorld('branchdeck', {
  sessionEnsure: id=>invoke('session-ensure',id),
  sessionCreate: (id,relative)=>invoke('session-create',id,relative),
  sessionSend: (id,launcherId,sessionId,fillOnly)=>invoke('session-send',id,launcherId,sessionId,fillOnly),
  sessionSnapshot: id=>invoke('session-snapshot',id),
  sessionInput: (id,data)=>invoke('session-input',id,data),
  sessionResize: (id,cols,rows)=>invoke('session-resize',id,cols,rows),
  sessionInterrupt: id=>invoke('session-interrupt',id),
  sessionClose: (id,confirmed)=>invoke('session-close',id,confirmed),
  filePreview: (id,relative)=>invoke('file-preview',id,relative),
  onSessionData: callback=>{const fn=(_,value)=>callback(value);ipcRenderer.on('session-data',fn);return ()=>ipcRenderer.removeListener('session-data',fn);},
  historyScan: () => invoke('history-scan'),
  historyFile: () => invoke('history-file'),
  historyImport: (scanId,selections) => invoke('history-import',scanId,selections),
  workspaceRemove:(id,scope)=>invoke('workspace-remove',id,scope),
  workspaceRestore:id=>invoke('workspace-restore',id),
  commandMove: (id,commandId,targetId,after)=>invoke('command-move',id,commandId,targetId,after),
  commandRemove: (id,commandId)=>invoke('command-remove',id,commandId),
  commandRestore: (id,commandId)=>invoke('command-restore',id,commandId),
  commandView: id => invoke('command-view',id),
  commandDecide: (id,commandId,decision) => invoke('command-decide',id,commandId,decision),
  discover: () => invoke('discover'),
  launchers: id => invoke('launchers', id),
  folders: (id, relative) => invoke('folders', id, relative),
  addRoot: () => invoke('add-root'),
  openWorkspace: id => invoke('workspace-open', id),
  launch: (workspaceId, launcherId) => invoke('launch', workspaceId, launcherId),
  snapshot: () => invoke('snapshot'),
  save: config => invoke('save', config),
  remove: id => invoke('remove', id),
  action: (id, action) => invoke('action', id, action),
  terminalSnapshot: id => invoke('terminal-snapshot', id),
  terminalInput: (id, runId, data) => invoke('terminal-input', id, runId, data),
  terminalResize: (id, runId, cols, rows) => invoke('terminal-resize', id, runId, cols, rows),
  onTerminal: callback => { const fn = (_, value) => callback(value); ipcRenderer.on('terminal', fn); return () => ipcRenderer.removeListener('terminal', fn); },
  logs: id => invoke('logs', id),
  pickDirectory: () => invoke('pick-directory'),
  openDirectory: id => invoke('open-directory', id),
  openLog: id => invoke('open-log', id),
  openData: () => invoke('open-data'),
  tools: () => invoke('tools'),
  onChange: callback => { const listener = () => callback(); ipcRenderer.on('change', listener); return () => ipcRenderer.removeListener('change', listener); },
  onLog: callback => { const listener = (_, value) => callback(value); ipcRenderer.on('log', listener); return () => ipcRenderer.removeListener('log', listener); }
});
